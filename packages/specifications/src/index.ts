/**
 * Shared ActionReceipt schema for cross-validation between kairos-guard and Kairos Cloud.
 * This is the canonical schema for deterministic action safety receipts.
 * 
 * Used by:
 * - kairos-guard (standalone safety firewall)
 * - Kairos Cloud (workflow execution audit trail)
 * 
 * All receipts generated by kairos-guard can be validated against Kairos Cloud audit logs
 * using this shared schema.
 */
export interface GuardActionReceipt {
  id: string                    // UUID
  tenant_id?: string            // Optional for standalone guard usage
  action_type: string           // 'email.send' | 'crm.note' | 'slack.post' etc.
  payload_hash: string          // SHA-256 of action payload — immutable audit
  timestamp: string             // ISO 8601
  allowed: boolean              // true = action allowed, false = blocked
  failed_rules: string[]        // Rule IDs that blocked the action (empty if allowed)
  outcome?: string              // For Kairos Cloud: 'policy_blocked' | 'executed' | 'dry_run'
  outcome_reason?: string       // Human-readable reason for block/dismiss
  dry_run?: boolean             // For Kairos Cloud: true if this was a simulation
  learning_suppressed?: boolean // For Kairos Cloud: true when learning was paused
}

